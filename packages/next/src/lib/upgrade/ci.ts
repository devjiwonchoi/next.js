import { existsSync } from 'fs'
import { mkdir, writeFile } from 'fs/promises'
import { dirname, join, relative, sep } from 'path'

import * as Log from '../../build/output/log'
import type { AgentUpgradePolicy } from '../../telemetry/events/agent-upgrade'
import { getAgentName } from '../../telemetry/agent-name'
import { bold, cyan } from '../picocolors'
import {
  chooseOption,
  findHarnesses,
  getHarnessDisplayName,
  type UpgradeHarness,
} from './harness'

// Generated workflows pin the action to a reviewed commit. Dependabot and
// Renovate keep the SHA current through the trailing version comment.
// TODO: Pin to the first release of vercel/next-upgrade.
const UPGRADE_ACTION_REPOSITORY = 'vercel/next-upgrade'
const UPGRADE_ACTION_COMMIT = '0000000000000000000000000000000000000000'
const UPGRADE_ACTION_VERSION = 'v1'

const WORKFLOW_PATH = '.github/workflows/next-upgrade.yml'

type CIAgent = UpgradeHarness['name']

const CI_AGENT_SECRETS: Record<CIAgent, string> = {
  claude: 'ANTHROPIC_API_KEY',
  codex: 'OPENAI_API_KEY',
}

function isCIAgent(value: unknown): value is CIAgent {
  return value === 'claude' || value === 'codex'
}

/**
 * Picks the agent the workflow runs. An explicit choice wins, then the agent
 * running this command, then the only installed agent CLI. Anything else asks
 * in a terminal and fails without one, since guessing would leave the user
 * with a workflow whose API key they don't have.
 */
async function resolveCIAgent(
  requested: string | true
): Promise<CIAgent | null> {
  if (requested !== true) {
    if (!isCIAgent(requested)) {
      throw new Error(
        `Unsupported CI agent ${JSON.stringify(requested)}. Expected "claude" or "codex".`
      )
    }
    return requested
  }

  const currentAgent = await getAgentName()
  if (isCIAgent(currentAgent)) {
    return currentAgent
  }

  const installed = (await findHarnesses()).map(({ name }) => name)
  if (installed.length === 1) {
    return installed[0]
  }

  if (!process.stdin.isTTY || !process.stdout.isTTY) {
    throw new Error(
      'Could not tell which coding agent should run upgrades in CI. Pass it explicitly:\n\n' +
        'next upgrade --ci=claude\n' +
        'next upgrade --ci=codex'
    )
  }

  const candidates: CIAgent[] =
    installed.length > 0 ? installed : ['claude', 'codex']
  const choice = await chooseOption(
    installed.length > 0
      ? 'Multiple coding agents detected. Which one should run upgrades in CI?'
      : 'Which coding agent should run upgrades in CI?',
    Object.fromEntries(
      candidates.map((name) => [name, getHarnessDisplayName(name)])
    ),
    0,
    true
  )
  return isCIAgent(choice) ? choice : null
}

function findGitRoot(directory: string): string | null {
  let current = directory
  while (true) {
    // `.git` is a file in worktrees and submodules.
    if (existsSync(join(current, '.git'))) {
      return current
    }
    const parent = dirname(current)
    if (parent === current) {
      return null
    }
    current = parent
  }
}

export function renderUpgradeWorkflow({
  agent,
  policy,
  workingDirectory,
}: {
  agent: CIAgent
  policy: AgentUpgradePolicy | null
  workingDirectory: string | null
}): string {
  const policyLine = policy
    ? `          policy: ${policy}`
    : `          # Defaults to \`experimental.agentUpgrade\` in your Next.js config.\n` +
      `          # policy: security # security | latest | experimental-future`
  const workingDirectoryLine = workingDirectory
    ? `\n          working-directory: ${workingDirectory}`
    : ''

  return `# Upgrades Next.js with a coding agent and opens a pull request with the result.
# Generated by \`next upgrade --ci\`. Edit it to fit your project.
name: Upgrade Next.js

on:
  schedule:
    # Every Monday at 09:00 UTC. Change the cron expression to run at another time.
    - cron: '0 9 * * 1'
  # Allows running the upgrade manually from the Actions tab.
  workflow_dispatch:

permissions:
  contents: write
  pull-requests: write

jobs:
  upgrade:
    runs-on: ubuntu-latest
    steps:
      - uses: ${UPGRADE_ACTION_REPOSITORY}@${UPGRADE_ACTION_COMMIT} # ${UPGRADE_ACTION_VERSION}
        with:
          agent: ${agent}
          api-key: \${{ secrets.${CI_AGENT_SECRETS[agent]} }}
${policyLine}${workingDirectoryLine}
`
}

export async function setupUpgradeCI(
  directory: string,
  options: { agent: string | true; policy: AgentUpgradePolicy | null }
): Promise<void> {
  const gitRoot = findGitRoot(directory)
  if (!gitRoot) {
    throw new Error(
      'No Git repository found. Run `next upgrade --ci` inside the repository that will run the workflow.'
    )
  }

  const workflowFile = join(gitRoot, WORKFLOW_PATH)
  if (existsSync(workflowFile)) {
    Log.warn(
      `${WORKFLOW_PATH} already exists. Edit it directly, or delete it and run this command again.`
    )
    return
  }

  const agent = await resolveCIAgent(options.agent)
  if (!agent) {
    return
  }

  // GitHub Actions paths always use forward slashes.
  const workingDirectory =
    relative(gitRoot, directory).split(sep).join('/') || null

  await mkdir(dirname(workflowFile), { recursive: true })
  await writeFile(
    workflowFile,
    renderUpgradeWorkflow({ agent, policy: options.policy, workingDirectory })
  )

  const secret = CI_AGENT_SECRETS[agent]
  Log.event(
    `Created ${bold(WORKFLOW_PATH)} to upgrade Next.js weekly with ${getHarnessDisplayName(agent)}.`
  )
  Log.bootstrap('')
  Log.bootstrap('  Next steps:')
  Log.bootstrap(
    `  1. Add the ${bold(secret)} repository secret: ${cyan(`gh secret set ${secret}`)}`
  )
  Log.bootstrap(
    '  2. Allow GitHub Actions to create pull requests in Settings > Actions > General.'
  )
  Log.bootstrap(`  3. Commit and push ${WORKFLOW_PATH}.`)
}
